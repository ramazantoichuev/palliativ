def seed_blocks(apps, schema_editor):
    """Создаёт блоки соглашения и заполняет пустые согласованным русским текстом.

    Менеджер не может создавать блоки в админке, поэтому их создаёт миграция.
    Уже заполненный блок не перезаписывается. Тексты на кыргызском и английском
    заказчик добавляет сам на вкладках языков.
    """
    EditableTextBlock = apps.get_model("main", "EditableTextBlock")
    for slug, text in TEXTS.items():
        block, _created = EditableTextBlock.objects.get_or_create(
            slug=slug, defaults={"content": text, "content_ru": text}
        )
        if not (block.content_ru or "").strip():
            block.content = text
            block.content_ru = text
            block.save()


def remove_seeded_blocks(apps, schema_editor):
    """Откат удаляет только блоки, текст которых остался таким, как в миграции."""
    EditableTextBlock = apps.get_model("main", "EditableTextBlock")
    for block in EditableTextBlock.objects.filter(slug__in=TEXTS):
        current = (block.content_ru or block.content or "").strip()
        if current in ("", TEXTS[block.slug].strip()):
            block.delete()


